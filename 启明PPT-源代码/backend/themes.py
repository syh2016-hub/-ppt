THEME_BY_ID = {theme["id"]: theme for theme in THEMES}
CATEGORIES = ["全部", "商务", "教育", "科技", "创意", "中国风", "简约", "高级", "自然"]
FEATURED_IDS = [theme["id"] for theme in THEMES if theme.get("featured")]


def _decorate(theme: dict[str, Any]) -> dict[str, Any]:
    item = copy.deepcopy(theme)
    colors = item["colors"]
    colors["on_primary"] = readable_on(colors["primary"])
    colors["on_accent"] = readable_on(colors["accent"])
    colors["cover_ink"] = readable_on(colors["bg"])
    colors["primary_dark"] = mix_color(colors["primary"], "#000000", 0.24)
    colors["primary_light"] = mix_color(colors["primary"], "#FFFFFF", 0.72)
    colors["bg_overlay"] = mix_color(colors["bg"], "#000000", 0.55 if colors["cover_ink"] == "#FFFFFF" else 0.06)
    item["is_dark"] = colors["cover_ink"] == "#FFFFFF"
    return item


def public_themes() -> list[dict[str, Any]]:
    return [_decorate(theme) for theme in THEMES]


def get_theme(template_id: str) -> dict[str, Any]:
    theme = THEME_BY_ID.get(template_id) or THEME_BY_ID["ink-paper"]
    return _decorate(theme)


def resolve_template(template_id: str, template: dict[str, Any] | None = None) -> dict[str, Any]:
    """Accept a built-in id or a validated online-template payload."""
    if template_id in THEME_BY_ID:
        return get_theme(template_id)
    if template and template.get("custom"):
        base = get_theme(str(template.get("base_id") or "ink-paper"))
        colors = dict(base["colors"])
        incoming = template.get("colors") or {}
        for key in ("bg", "bg2", "surface", "surface_alt", "ink", "muted", "primary", "accent", "line"):
            value = str(incoming.get(key, "")).strip()
            if value.startswith("#") and len(value) in (4, 7):
                colors[key] = value.upper()
        base["colors"] = colors
        base["id"] = str(template.get("id") or template_id)
        base["name"] = str(template.get("name") or "在线灵感模板")[:40]
        base["custom"] = True
        base["cover_image_url"] = str(template.get("image_url") or "")
        base["source_url"] = str(template.get("source_url") or "")
        base["motif"] = str(template.get("motif") or "wave")
        base["cover_style"] = str(template.get("cover_style") or "split")
        return _decorate(base)
    return get_theme("ink-paper")


def theme_css_vars(theme: dict[str, Any]) -> dict[str, str]:
    colors = theme["colors"]
    return {f"--{key.replace('_', '-')}": value for key, value in colors.items()}
